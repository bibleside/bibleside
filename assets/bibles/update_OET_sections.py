# Script to automatically generate a dart file mapping the OET-RV sections from the OET json files
# Requirements: Python 3 and the standard library

# The resulting oet_rv_section_headings.dart file is formatted like so:
#
# Map<String, List<List<String>>> sectionHeadingsMappingForOET = {
#   'JHN': [
#     [
#       '1:1 First section',
#       '1:1 Alternative heading; Another alternative heading',
#     ],
#     [
#       '1:21 Second section',
#     ],
#   ],
# };

import os
import re
import json

RV_local_path = "./OET-RV/"
oet_rv_section_headings_file = "../../lib/common/oet_rv_section_headings.dart"
pubspec_file = "../../pubspec.yaml"

section_headings_dart_file_template = """// GENERATED FILE. DO NOT EDIT DIRECTLY
// This file can be regenerated by running the update_OET_sections.py file

Map<String, List<List<String>>> sectionHeadingsMappingForOET = {{
{}
}};
"""

# Paragraphs that can sit between two paragraphs of verse text
heading_markers = re.compile(r'(s|ms)\d?|mr|r|d|sp|qa|cl|b|rem')

# Edit marks at the start of an added phrase, hidden in the reader
add_edit_marks = re.compile(r'^[?!#$%&*^≈≡@]+')


def generate_headings_mappings_file():
  sections_mapping = {}
  bundled_books = bundled_book_codes()

  for file in sorted(os.listdir(RV_local_path)):
    book_code = file.split('.')[0]
    if book_code not in bundled_books:
      continue

    data = read_json_file(f'{RV_local_path}{file}')
    book_sections = sections_for_book(data['content'])

    if len(book_sections) != 0:
      sections_mapping[book_code] = book_sections

  contents = section_headings_dart_file_template.format(dart_mapping(sections_mapping))

  with open(oet_rv_section_headings_file, "w") as file:
    file.write(contents)


def sections_for_book(content):
  # A heading starts at the verse that follows it,
  # or at the current verse if the paragraph after it continues a verse.
  book_sections = []
  headings = []
  chapter_number = None
  verse_number = None

  for item in content:
    if item.get('type') == 'chapter':
      chapter_number = item['number']
      verse_number = None
      continue

    if chapter_number is None or item.get('type') != 'para':
      continue

    marker = item['marker']

    if heading_markers.fullmatch(marker):
      text = text_of(item)

      if marker == 's1':
        headings.append(text)
      elif marker == 'rem' and text.startswith('/s1 ') and len(headings) != 0:
        headings.append(text.removeprefix('/s1 '))
      continue

    first_verse = first_verse_number(item)
    if first_verse is not None:
      verse_number = first_verse

    if len(headings) != 0:
      start_verse = verse_number or '1'
      book_sections.append([format_section(chapter_number, start_verse, heading) for heading in headings])
      headings = []

    verse_number = last_verse_number(item) or verse_number

  return book_sections


def text_of(item):
  text = ''
  for part in item.get('content', []):
    if type(part) == str:
      text += part
    elif part.get('type') == 'char':
      text += add_edit_marks.sub('', text_of(part)) if part['marker'] == 'add' else text_of(part)
  return ' '.join(text.split())


def first_verse_number(para):
  content = para.get('content', [])
  if len(content) != 0 and is_verse(content[0]):
    return start_of_verse_range(content[0]['number'])
  return None


def last_verse_number(para):
  verses = [part['number'] for part in para.get('content', []) if is_verse(part)]
  return start_of_verse_range(verses[-1]) if len(verses) != 0 else None


def is_verse(part):
  return type(part) == dict and part.get('type') == 'verse'


def start_of_verse_range(number):
  return re.match(r'\d+', number).group(0)


def format_section(chapterNumber, verseNumber, section):
  return f'{chapterNumber}:{verseNumber} {section}'


def dart_mapping(sections_mapping):
  books = []
  for book_code, book_sections in sections_mapping.items():
    sections = ',\n'.join(dart_section(section) for section in book_sections)
    books.append(f"  '{book_code}': [\n{sections},\n  ],")
  return '\n'.join(books)


def dart_section(section):
  return '    [' + ', '.join(dart_string(heading) for heading in section) + ']'


def dart_string(text):
  text = text.replace('\\', '\\\\').replace('$', '\\$')
  if "'" in text and '"' not in text:
    return f'"{text}"'
  return "'" + text.replace("'", "\\'") + "'"


def bundled_book_codes():
  with open(pubspec_file, "r") as file:
    return re.findall(r'assets/bibles/OET-RV/(\w+)\.json', file.read())


def read_json_file(path):
  with open(path, "r") as json_file:
    data = json.load(json_file)

    return data


if __name__ == "__main__":
  print("Generating file...")
  generate_headings_mappings_file()
  print("Generating complete.")
